const SUPPORTED = Object.keys(translations);

function detectLang() {
  const params = new URLSearchParams(window.location.search);
  const fromQuery = params.get("lang");
  if (fromQuery && SUPPORTED.includes(fromQuery)) return fromQuery;

  const stored = localStorage.getItem("iqsoftcore-lang");
  if (stored && SUPPORTED.includes(stored)) return stored;

  const browser = (navigator.language || "fi").slice(0, 2).toLowerCase();
  return SUPPORTED.includes(browser) ? browser : "fi";
}

function applyTranslations(lang) {
  const t = translations[lang] || translations.fi;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key] != null) el.textContent = t[key];
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const mapping = el.getAttribute("data-i18n-attr").split(",");
    mapping.forEach((pair) => {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && key && t[key] != null) el.setAttribute(attr, t[key]);
    });
  });

  const titleEl = document.querySelector("title");
  if (titleEl && t.metaTitle) titleEl.textContent = t.metaTitle;

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && t.metaDescription) metaDesc.setAttribute("content", t.metaDescription);

  const select = document.getElementById("lang-select");
  if (select) select.value = lang;

  localStorage.setItem("iqsoftcore-lang", lang);

  const url = new URL(window.location.href);
  url.searchParams.set("lang", lang);
  window.history.replaceState({}, "", url);

  if (typeof renderPrivacyPolicy === "function") {
    renderPrivacyPolicy(lang);
  }
}

function initI18n() {
  const lang = detectLang();
  applyTranslations(lang);

  const select = document.getElementById("lang-select");
  if (select) {
    select.addEventListener("change", (e) => {
      applyTranslations(e.target.value);
    });
  }
}

document.addEventListener("DOMContentLoaded", initI18n);
