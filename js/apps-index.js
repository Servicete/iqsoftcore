function escapeAppsIndexHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function renderAppsPage(lang) {
  const root = document.getElementById("apps-root");
  if (!root || typeof APPS_INDEX === "undefined") return;

  const page = APPS_INDEX[lang] || APPS_INDEX.en || APPS_INDEX.fi;
  const titleEl = document.querySelector("title");
  if (titleEl && page.metaTitle) titleEl.textContent = page.metaTitle;

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && page.metaDescription) metaDesc.setAttribute("content", page.metaDescription);

  const cards = page.products
    .map(([href, name, blurb]) => {
      const safeHref = escapeAppsIndexHtml(href);
      const safeName = escapeAppsIndexHtml(name);
      return `<article class="product-card">
        <h2><a href="${safeHref}">${safeName}</a></h2>
        <p>${escapeAppsIndexHtml(blurb)}</p>
        <div class="card-actions"><a class="btn btn-ghost" href="${safeHref}">${escapeAppsIndexHtml(page.openPage)}</a></div>
      </article>`;
    })
    .join("");

  root.innerHTML = `<h1>${escapeAppsIndexHtml(page.title)}</h1>
    <p class="apps-intro">${escapeAppsIndexHtml(page.intro)}</p>
    <div class="product-grid">${cards}</div>`;
}
